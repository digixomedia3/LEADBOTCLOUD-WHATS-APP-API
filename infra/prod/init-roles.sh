#!/bin/sh
# Production roles. Passwords come from /etc/lbc/db.env, never from the repository.
set -e
psql -v ON_ERROR_STOP=1 -U postgres -d leadbotcloud <<SQL
CREATE ROLE owner  LOGIN PASSWORD '${OWNER_PASSWORD}'  NOSUPERUSER NOBYPASSRLS;
CREATE ROLE app    LOGIN PASSWORD '${APP_PASSWORD}'    NOSUPERUSER NOBYPASSRLS NOINHERIT;
CREATE ROLE worker LOGIN PASSWORD '${WORKER_PASSWORD}' NOSUPERUSER BYPASSRLS NOINHERIT;
GRANT ALL ON DATABASE leadbotcloud TO owner;
GRANT CONNECT ON DATABASE leadbotcloud TO app, worker;
ALTER SCHEMA public OWNER TO owner;
GRANT USAGE ON SCHEMA public TO app, worker;
ALTER DEFAULT PRIVILEGES FOR ROLE owner IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO app, worker;
ALTER DEFAULT PRIVILEGES FOR ROLE owner IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO app, worker;
SQL
